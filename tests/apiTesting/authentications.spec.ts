//API Key Auth - Mostly these are related to query parameter. So, we need to pass them through params option
test("API Key Auth1", async ({ request }) => {

    const response = await request.get("https://openweathermap.org/", {
        params: {
            q: "Hyderabad", //q is the parameter given by developers, where we need to use that
            appid: "GENERATEDAPIKEY" // appid is the API key need to provide, which was specified by dev team. It differs
        }
    });

    expect(response.ok()).toBeTruthy();
    expect(response.status()).toBe(200);
    const responseBody = response.json();
    console.log("API Key Response is ======>", responseBody);


})
